import assert from 'node:assert/strict';
import {driverStationPose} from '../dist/driver-camera.js';
const blue={alliance:'blue'},red={alliance:'red'},start={x:-5,y:.4,z:0};
const initial=driverStationPose(null,start,blue,16.54,0);
assert(initial.eye.x < -16.54/2);
assert.equal(initial.eye.y,1.75);
const moved=driverStationPose(initial,{x:4,y:.5,z:3},blue,16.54,1/60);
assert.deepEqual(moved.eye,initial.eye,'the driver stays at the station');
assert(Math.abs(moved.yaw-initial.yaw)<=2.6/60,'neck turn speed is limited');
assert(Math.abs(moved.pitch-initial.pitch)<=1.8/60);
assert.deepEqual(driverStationPose(initial,start,blue,16.54,0),initial);
const target={x:1,y:.4,z:1};
const run=fps=>{let p=initial;for(let i=0;i<fps;i++)p=driverStationPose(p,target,blue,16.54,1/fps);return p;};
assert(Math.abs(run(30).yaw-run(144).yaw)<.003,'tracking is independent of frame rate');
const mirrored=driverStationPose(initial,{x:5,y:.4,z:0},red,16.54,0);
assert.equal(mirrored.eye.x,-initial.eye.x);
assert.equal(mirrored.eye.z,-initial.eye.z);
assert(Math.abs(mirrored.target.x-mirrored.eye.x+initial.target.x-initial.eye.x)<1e-10);
console.log('PASS driver station: fixed eye, smooth tracking, frame rates, alliance switch');
