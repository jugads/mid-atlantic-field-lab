import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {Simulation}=require('../dist/physics.js');
const {resolve}=require('../dist/team-presets.js');
const {MultiplayerClient}=await import('../dist/multiplayer.js');
const sim=new Simulation();sim.enableMultiplayer([resolve('341'),resolve('316','red')]);sim.start();
const client=new MultiplayerClient(()=>{});client.id='a';client.state='connected';client.rtt=100;
client.room={status:'playing',players:[{id:'a'},{id:'b'}]};
const data={started:true,running:true,time:1,scores:{blue:0,red:0},fleet:sim.fleet.map(e=>({config:e.config,robot:{...e.robot},inventory:e.inventory,turretAngle:e.robot.a,intake:false})),balls:[]};
client.frames=[{at:1000,data}];const x=data.fleet[0].robot.x;
client.apply(sim,1000,{moveX:1});assert(sim.robot.x>x,'local input predicts movement immediately');
assert.equal(data.fleet[0].robot.x,x,'prediction does not change the authoritative snapshot');
client.room.status='paused';client.apply(sim,1010,{moveX:1});assert.equal(sim.robot.x,x,'prediction stops when paused');
const host=new MultiplayerClient(()=>{});host.id='a';host.state='connected';host.room={status:'playing',hostId:'a',players:[{id:'a'},{id:'b'}]};
host.hostSim=new Simulation();host.hostSim.enableMultiplayer([resolve('341'),resolve('316','red')]);
const sent=[];host.send=m=>sent.push(m);host.guestInput={moveX:-1};host.guestInputAt=1000;
const bx=host.hostSim.fleet[1].robot.x;host.advanceHost(1000,{});host.advanceHost(1100,{});
assert(host.hostSim.time>0,'host advances match');assert(host.hostSim.fleet[1].robot.x<bx,'relayed guest controls drive guest robot');
assert(sent.some(m=>m.type==='snapshot'&&m.fleet.length===2),'host publishes shared snapshots');
assert(JSON.stringify(sent.at(-1)).length<65536,'snapshot fits relay payload limit');
const before=host.hostSim.time;host.room.status='paused';host.advanceHost(1200,{});host.advanceHost(1300,{});assert.equal(host.hostSim.time,before,'paused host does not advance');
console.log('PASS local movement prediction remains separate from authoritative state');
